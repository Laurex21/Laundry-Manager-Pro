import assert from "node:assert/strict";
import { randomBytes, randomUUID } from "node:crypto";
import { eq } from "drizzle-orm";
import { storefrontFixture } from "../../scripts/storefront-fixture";
import { calculateStorefrontQuote } from "./storefront-pricing";
import { PILOT_WEIGHTS } from "../../shared/storefront";
import { StorefrontService } from "./storefront-service";
import type { db } from "../db";

const f = await storefrontFixture(), slug = "pressing-horizon";
const { service, actor, schema, database } = f;
let checks = 0;
const check = (condition: unknown, message: string) => { assert.ok(condition, message); checks++; };
const rejects = async (fn: () => Promise<unknown>, status: number) => { await assert.rejects(fn, (e: any) => e.status === status); checks++; };
const lines = [
  { serviceId: 1, garment: "tshirt", size: "child", count: 3 },
  { serviceId: 1, garment: "shirt", size: "adult", count: 2 },
  { serviceId: 1, garment: "jeans", size: "teen", count: 1 },
];
const input = async (cart = lines) => ({ lines: cart, requestKey: randomUUID(), trackingSecret: randomBytes(32).toString("hex"), quoteFingerprint: (await service.quote(slug, { lines: cart })).fingerprint, customerName: "Client test", phone: "+237600000001", note: "Données fictives" });
const find = async (reference: string) => (await database.select().from(schema.storefrontRequests).where(eq(schema.storefrontRequests.reference, reference)))[0];
try {
  const quote = await service.quote(slug, { lines });
  check(quote.total === "1300" && quote.estimatedGrams === 1300, "mixed size estimate is exactly 1.3 kg / 1300 XAF");
  const fractional = calculateStorefrontQuote({ lines: [{ ...lines[0], count: 1 }] }, [{ id: 1, name: "decimal", description: null, price: "12.340000", minimumCharge: null, mode: "kg" }], PILOT_WEIGHTS, "EUR", 1);
  check(fractional.total === "1.234", "exact decimal multiplication, trailing DB zeroes accepted");
  await rejects(() => service.quote(slug, { lines: [{ ...lines[0], serviceId: 4 }] }), 409);
  const evening = await service.quote(slug, { lines: [{ ...lines[0], garment: "evening_dress" }] });
  check(evening.total === null && evening.estimatedGrams === null, "unknown weight is never free or zero");
  const custom = await service.quote(slug, { lines: [{ ...lines[0], serviceId: 3 }] });
  check(custom.total === null, "quote-only service is not zero-priced");
  const body = await input();
  const submissions = await Promise.all([service.submit(slug, body), service.submit(slug, body)]);
  check(submissions[0].reference === submissions[1].reference, "concurrent retries create one request");
  await rejects(() => service.submit(slug, { ...body, note: "altered" }), 409);
  const req = await find(submissions[0].reference);
  check(req.trackingHash !== body.trackingSecret, "only the hash of tracking secret is stored");
  const stranger = { siteId: 2, organisationId: 2, userId: "other-demo" };
  await rejects(() => service.detail(stranger, req.id), 404);
  await rejects(() => service.disposition(stranger, req.id, 1, true, "test"), 404);
  await rejects(() => service.tracking("a".repeat(64)), 404);
  await rejects(() => service.convert(actor, req.id, 1), 409);
  const detail = await service.detail(actor, req.id);
  check(!("trackingHash" in detail) && !("requestKey" in detail), "staff response excludes tracking credentials");
  const tracked = await service.tracking(body.trackingSecret);
  check(!("phone" in tracked) && !("customerName" in tracked), "guest response exposes only the required tracking data");
  await service.disposition(actor, req.id, 1, true, "Dépôt accepté");
  await rejects(() => service.disposition(actor, req.id, 1, true, "again"), 409);
  await rejects(() => service.review(actor, req.id, { expectedVersion: 2, received: true, basis: "measured", measuredGrams: {}, note: "Pesée" }), 400);
  await service.review(actor, req.id, { expectedVersion: 2, received: true, basis: "measured", measuredGrams: { 1: 1450 }, note: "Pesée sans sac : 1,45 kg" });
  check((await service.tracking(body.trackingSecret)).finalQuote?.total === "1450", "measured final amount is correct");
  await rejects(() => service.decision(body.trackingSecret, 2, true), 409);
  await service.decision(body.trackingSecret, 3, true);
  await service.review(actor, req.id, { expectedVersion: 3, received: true, basis: "conventional", note: "Forfait convenu au barème" });
  await rejects(() => service.convert(actor, req.id, 3), 409);
  check((await service.tracking(body.trackingSecret)).status === "awaiting_customer_approval", "revision revokes previous agreement");
  await service.decision(body.trackingSecret, 4, true);
  await database.update(schema.services).set({ price: "2000" }).where(eq(schema.services.id, 1));
  const failed = new StorefrontService(database as unknown as typeof db, async () => { throw new Error("simulate analytics failure"); });
  await assert.rejects(() => failed.convert(actor, req.id, 4)); checks++;
  check((await database.select().from(schema.orders)).length === 0, "failed conversion rolls back order creation");
  check((await database.select().from(schema.customers)).length === 0, "failed conversion rolls back new customer too");
  const conversions = await Promise.all([service.convert(actor, req.id, 4), service.convert(actor, req.id, 4)]);
  check(conversions[0].orderId === conversions[1].orderId, "concurrent conversion produces exactly one order");
  const [order] = await database.select().from(schema.orders);
  const [item] = await database.select().from(schema.orderItems);
  check(Number(order.totalAmount) === 1300 && Number(item.priceAtOrder) === 1000 && Number(item.quantity) === 1.3, "accepted prices survive catalogue changes");
  check(order.paymentStatus === "unpaid" && (await database.select().from(schema.payments)).length === 0, "accepting a quote does not take a payment");
  check((await database.select().from(schema.garmentItems)).reduce((n, g) => n + g.quantity, 0) === 6, "physical piece count is distinct from kg quantity");
  check((await service.tracking(body.trackingSecret)).order?.reference === order.orderReference, "guest follows actual order after conversion");
  await rejects(() => service.decision(body.trackingSecret, 4, false), 409);
  const stale = await input();
  await database.update(schema.services).set({ minimumCharge: "4000" }).where(eq(schema.services.id, 1));
  await rejects(() => service.submit(slug, stale), 409);
  const minBody = await input(), minReq = await find((await service.submit(slug, minBody)).reference);
  check(minReq.estimate.total === "4000" && minReq.estimate.lots.length === 1, "minimum applies once for a service lot");
  await service.disposition(actor, minReq.id, 1, true, "OK dépôt");
  await service.review(actor, minReq.id, { expectedVersion: 2, received: true, basis: "measured", measuredGrams: { 1: 1450 }, note: "Pesée" });
  await service.decision(minBody.trackingSecret, 3, true);
  const minOrder = await service.convert(actor, minReq.id, 3);
  const minItems = await database.select().from(schema.orderItems).where(eq(schema.orderItems.orderId, minOrder.orderId));
  check(minItems.length === 2 && minItems.reduce((n, i) => n + Number(i.quantity) * Number(i.priceAtOrder), 0) === 4000, "receipt lines exactly reconcile including minimum supplement");
  const unknownBody = await input([{ ...lines[0], garment: "evening_dress" }]);
  const unknown = await find((await service.submit(slug, unknownBody)).reference);
  await service.disposition(actor, unknown.id, 1, true, "À peser");
  await rejects(() => service.review(actor, unknown.id, { expectedVersion: 2, received: true, basis: "conventional", note: "Forfait" }), 400);
  const config = (await service.admin(actor)).shop!;
  await rejects(() => service.save(actor, { ...config, expectedVersion: 1, services: [{ serviceId: 4, mode: "kg" }] }), 400);
  await service.save(actor, { ...config, expectedVersion: config.version, published: false });
  await rejects(() => service.publicShop(slug), 404);
  check((await service.tracking(body.trackingSecret)).status === "converted", "closing storefront preserves existing tracking");
  console.log(`Storefront integration: ${checks} checks passed; reviewed migration applied to isolated PostgreSQL.`);
} finally { await f.pg.close(); }
