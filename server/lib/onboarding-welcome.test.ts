import assert from 'node:assert/strict';
import { recordWelcomeEligibility, consumeRegistrationWelcome, welcomeKey } from '../../client/src/lib/onboarding-welcome';
const data = new Map<string, string>();
const storage = { getItem: (k: string) => data.get(k) ?? null, setItem: (k: string,v: string) => { data.set(k,v); }, removeItem: (k: string) => { data.delete(k); } };
assert.equal(consumeRegistrationWelcome(storage,'existing-owner'),false,'Missing old progress is not a new registration');
data.set('xpresspro-getting-started-active-v1:existing-owner','1');
assert.equal(consumeRegistrationWelcome(storage,'existing-owner'),false,'Legacy active flag must not restart a tutorial');
recordWelcomeEligibility(storage,'new-owner',true);
assert.equal(consumeRegistrationWelcome(storage,'other-owner'),false);
assert.equal(consumeRegistrationWelcome(storage,'new-owner'),true);
assert.equal(consumeRegistrationWelcome(storage,'new-owner'),false,'Reload/remount must not repeat welcome');
recordWelcomeEligibility(storage,'new-owner',false);
assert.equal(consumeRegistrationWelcome(storage,'new-owner'),false,'A later login is never a new registration');
recordWelcomeEligibility(storage,'interrupted-registration',true);
recordWelcomeEligibility(storage,'interrupted-registration',false);
assert.equal(data.has(welcomeKey('interrupted-registration')),false,'Login clears any stale registration signal');
const blocked = { getItem: () => { throw Error('blocked'); }, setItem: () => { throw Error('blocked'); }, removeItem: () => { throw Error('blocked'); } };
assert.doesNotThrow(()=>recordWelcomeEligibility(blocked,'new-owner',true));
assert.equal(consumeRegistrationWelcome(blocked,'new-owner'),false);
console.log('PASS onboarding welcome: registration only, once, account isolation, stale login/legacy flags ignored, storage failure does not break authentication');
