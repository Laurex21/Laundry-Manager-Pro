export type Currency = (typeof CURRENCIES)[number]["code"];
export type CurrencyLanguage = keyof (typeof CURRENCIES)[number]["names"];

export const DEFAULT_CURRENCY: Currency = "XAF";
export const SUPPORTED_CURRENCIES = new Set<Currency>(CURRENCIES.map((currency) => currency.code));

export function currencyByCode(code: Currency) {
  return CURRENCIES.find((currency) => currency.code === code) ?? CURRENCIES[0];
}

export function currencyName(code: Currency, language?: string) {
  const locale: CurrencyLanguage = language?.startsWith("fr") ? "fr" : language?.startsWith("pt") ? "pt" : "en";
  return currencyByCode(code).names[locale];
}

export function currencyPrefix(code: Currency) {
  return `${currencyByCode(code).symbol} `;
}

export function normalizeCurrency(value: unknown): Currency {
  if (value === "FCFA") return "XAF";
  return typeof value === "string" && SUPPORTED_CURRENCIES.has(value as Currency)
    ? (value as Currency)
    : DEFAULT_CURRENCY;
}
